export function getDeviceCapabilities(
  device: Device,
  context: CapabilityContext,
) {
  const list = CAPABILITIES[device.kind] ?? [];
  return list
    .filter((cap) => (cap.contexts ?? DEFAULT_CONTEXTS).includes(context))
    .sort((a, b) => (a.order ?? 0) - (b.order ?? 0));
}
